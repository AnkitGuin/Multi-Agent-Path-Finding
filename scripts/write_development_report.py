"""Write the research decision report exclusively from stored measured data."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    study = ROOT/"results/async/development_2026_11_17"
    data = json.loads((study/"tables/analysis.json").read_text())
    legacy = json.loads((ROOT/"results/recertified_2026_11_17/comparison_summary.json").read_text())
    overall = {r["method"]: r for r in data["overall"]}
    paired = {(r["method_b"], r["metric"]): r for r in data["paired_controls"]}
    table = ["| Controller | Episodes | Success | Conflict episodes | Mean completion | Mean sent KiB |",
             "|---|---:|---:|---:|---:|---:|"]
    for row in data["overall"]:
        table.append(f"| {row['method']} | {row['n']} | {row['success']} | {row['collisions']} | "
                     f"{row['mean_completion']:.3f} | {row['mean_bytes']/1024:.2f} |")
    byte = paired[("claims_periodic", "bytes_sent")]
    waits = paired[("claims_periodic", "total_wait_time")]
    cost = paired[("claims_periodic", "executed_time_soc")]
    reduction = 100*(1-overall["claims_selective"]["mean_bytes"]/overall["claims_periodic"]["mean_bytes"])
    witness_path = study/"failure_cases/oracle_feasible_witness.json"
    case_note = "Qualitative witness generation has not been run."
    if witness_path.exists():
        witness = json.loads(witness_path.read_text())
        case_note = (f"The explicitly selected failed local episode completed {witness['local_completion']:.0%} "
                     f"of agents by the horizon. A full-information dependency execution of a CBS plan "
                     f"completed all agents in {witness['elapsed_time']:.2f} seconds without resource conflicts. "
                     "This is an executable feasibility witness, not a matched baseline comparison. "
                     "Selection criteria, full reference actions and success/failure figures are stored in "
                     "results/async/development_2026_11_17/failure_cases. It shows why local noncompletion "
                     "cannot be attributed only to globally infeasible test cases.")
    text = f"""# Development evidence and stop/go decision — 2026-11-17

This report is generated by `scripts/write_development_report.py`. It is an
engineering/research decision report, not a manuscript or novelty assertion.

## Executed design

{data['verified_replays']} paired controller runs, seven families, ten seeds,
three latency/loss/duration settings and seven controllers. Every replay was
independently checked, including failed runs. Main procedural cases use five
agents; hand-designed adversarial cases use two. Grid size is 16 for procedural
cases; horizon 40 seconds, sensing two hops, transport three hops. No tuning
sweep or final holdout was run. Full config and source hashes are in the run
manifest; all replay files are stored as compressed JSON.

## Descriptive results (all episodes)

{chr(10).join(table)}

All five claim controls recorded zero conflicts in their 1,050 episodes. This
is empirical validation under exact sensing/cooperative-policy assumptions,
not an unconditional safety theorem. Low completion is a substantial limitation:
safe waiting, lost coordination and narrow/permanent-goal passages can prevent
progress. A timeout does not prove a deadlock or global infeasibility.
Some deliberately pathological cases are unsolvable even for stronger methods.

The mixed-family totals are descriptive, not a general algorithm ranking.
An unsafe controller's completed-agent fraction is not a collision-free success
rate. Native PIBT/Causal-PIBT references use stronger/different assumptions and
are reported separately in `research/baselines.md`.

## Paired selective versus periodic reporting

Mean sent bytes decrease by {reduction:.2f}% as a ratio of all-episode means.
Paired absolute difference (selective minus periodic) is
{byte['mean_a_minus_b']:.2f} bytes, with an exploratory map-cluster 95% bootstrap
interval [{byte['map_bootstrap_low']:.2f}, {byte['map_bootstrap_high']:.2f}].
The bootstrap uses {byte['distinct_maps']} distinct true maps and 2,000 seeded
draws. It does not resample individual agents, frames or repeated message events.

Waiting difference is {waits['mean_a_minus_b']:.4f} seconds, interval
[{waits['map_bootstrap_low']:.4f}, {waits['map_bootstrap_high']:.4f}]. Censored time-SOC
difference is {cost['mean_a_minus_b']:.4f}, interval
[{cost['map_bootstrap_low']:.4f}, {cost['map_bootstrap_high']:.4f}]. Both include zero.
Success is {overall['claims_selective']['success']}/{overall['claims_selective']['n']}
versus {overall['claims_periodic']['success']}/{overall['claims_periodic']['n']}.
This does not establish a reliable waiting/travel improvement. Wilson intervals
by condition and all ablation differences are in generated CSVs. Comparisons
are exploratory without multiplicity correction or confirmatory generalization.

## Hypothesis decisions

- H1: not supported by this development evidence; waiting interval crosses zero.
- H2: no established delay-interaction effect; not confirmed or claimed.
- H3: not tested, because no topology-aware component was implemented.
- H4: byte reduction is observed in development, but selectivity alone is
  established prior art and is not a novel contribution.
- Incremental repair has a measured development effect relative to full replan;
  see paired controls. This is not a tuned holdout or isolated modern-baseline win.

## Qualitative success and failure

{case_note}

## Full legacy recertification

All {legacy['rows']} configured jobs were rerun without replacing historical raw
files. Invalid returned plans: {legacy['invalid_runs']}. Exact historical status/SOC
matches: {legacy['exact_status_soc_matches']}. Differences are stored per job.
Timeout outcomes depend on host load and ten-second budget; the asynchronous
development study overlapped the final legacy suite. The historical REPORT was
retained and its tables were not silently replaced.

## Gate decision and next direction

G1 remains unpassed for a new methods claim: the prototype is standard local
claims plus a reporting threshold. G3 is partial: two authentic native reference
implementations are reproduced, but a strong modern same-information local
competitor is still missing. G4 does not support the proposed waiting-efficiency
claim. Therefore preserve this negative/inconclusive result, leave the reserved
final holdout untouched, and do not start an improvement manuscript or optional
learned component. This follows the roadmap's stop/go rules.

Next useful research: implement/audit progress recovery under the same partial
information and packet assumptions, compare with an explicitly adapted
Causal-PIBT/online-repair baseline, and test whether freshness still adds value
after dominant progress failures are controlled. Resolve LSRP's compiler
and license issues independently. A full systematic literature sweep, real
robot model, high-agent-count scaling and independent scientific reviews remain
uncompleted. No publication readiness is asserted.
"""
    (ROOT/"research/reports/development_results.md").write_text(text, encoding="utf-8")
    print("wrote measured development result and gate decision report")


if __name__ == "__main__":
    main()
